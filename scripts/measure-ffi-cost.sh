#!/usr/bin/env bash
# Measure what the fofoca FFI costs mallorca: binary size, CPU, RAM.
# Regenerates every number in docs/ffi-cost.md. See that doc for the findings.
#
#   ./scripts/measure-ffi-cost.sh size      # binary size + per-crate attribution
#   ./scripts/measure-ffi-cost.sh runtime   # CPU/RAM scenario matrix (needs a display)
#   ./scripts/measure-ffi-cost.sh all
#
# Env knobs: DURATION (default 60s per run), REPEATS (default 5), OUT (bin/measure).
#
# The size baseline is a scratch-tree build: src/ is copied out and mesh.odin is
# replaced by a pure-Odin stub with the identical surface but no `foreign import`,
# so p2p.odin and main.odin compile unchanged and the only difference between the
# two binaries is the Rust archive. The repo is never modified.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

OUT="${OUT:-$ROOT/bin/measure}"
WORK="$OUT/work"
DURATION="${DURATION:-60}"
REPEATS="${REPEATS:-5}"
DEFINES=(-define:KARL2D_AUDIO_BACKEND=nil)
GRID="${GRID:-examples/_midi.orca}"

mkdir -p "$OUT" "$WORK"

log() { printf '\033[1;36m==>\033[0m %s\n' "$*" >&2; }
bytes() { stat -f%z "$1"; }

#-----------------------------------------------------------------------------#
# environment provenance — so a stale table is identifiable later
#-----------------------------------------------------------------------------#
record_env() {
	{
		echo "date	$(date -u +%Y-%m-%dT%H:%M:%SZ)"
		echo "model	$(sysctl -n hw.model)"
		echo "cpus	$(sysctl -n hw.ncpu)"
		echo "memory_bytes	$(sysctl -n hw.memsize)"
		echo "macos	$(sw_vers -productVersion)"
		echo "odin	$(odin version 2>&1 | head -1)"
		echo "rustc	$(rustc --version 2>&1 | head -1)"
		echo "git_rev	$(git rev-parse --short HEAD)"
		echo "git_dirty	$(git status --porcelain | wc -l | tr -d ' ')"
		echo "refresh_hz	$(system_profiler SPDisplaysDataType 2>/dev/null |
			awk -F': ' '/UI Looks|Refresh Rate/{print $2; exit}' || echo unknown)"
	} >"$OUT/env.tsv"
	log "environment recorded -> $OUT/env.tsv"
}

#-----------------------------------------------------------------------------#
# no-mesh baseline tree
#-----------------------------------------------------------------------------#
# Mirrors src/fofoca.odin's entire surface — same types, same proc names, same
# signatures, same helpers — as ordinary Odin returning nil/0/"". If mesh.odin
# gains or changes a symbol, this build fails to compile rather than silently
# measuring the wrong thing.
write_nomesh_stub() {
	cat >"$1" <<'ODIN'
// GENERATED by scripts/measure-ffi-cost.sh — not part of the app.
// Stands in for src/fofoca.odin with no `foreign import`, so the baseline binary
// links none of libfofoca_ffi.a while p2p.odin/main.odin compile
// verbatim. Kept signature-for-signature in step with src/fofoca.odin: a drift
// shows up as a compile error here, not as a silently wrong measurement.
#+build darwin
package main

import "core:c"
import "core:mem"
import "core:strings"

Fofoca_Pipe :: struct {}

Fofoca_Opts :: struct {
	mesh:      cstring,
	topic:     cstring,
	nick:      cstring,
	name:      cstring,
	is_public: c.int,
	mdns:      c.int,
	dht:       c.int,
	relay:     c.int,
	max_peers: c.size_t,
}

Fofoca_Frame :: struct {
	nick:     [64]u8,
	directed: c.int,
	eof:      c.int,
	len:      c.size_t,
}

fofoca_open :: proc "c" (opts: ^Fofoca_Opts) -> ^Fofoca_Pipe {return nil}
fofoca_id :: proc "c" (h: ^Fofoca_Pipe) -> cstring {return nil}
fofoca_name :: proc "c" (h: ^Fofoca_Pipe) -> cstring {return nil}
fofoca_nickname :: proc "c" (h: ^Fofoca_Pipe) -> cstring {return nil}
fofoca_recv :: proc "c" (
	h: ^Fofoca_Pipe,
	buf: [^]u8,
	cap: c.size_t,
	timeout_ms: c.int,
	frame: ^Fofoca_Frame,
) -> c.long {return 0}
fofoca_send :: proc "c" (h: ^Fofoca_Pipe, to: cstring, buf: [^]u8, len: c.size_t) -> c.long {return 0}
fofoca_send_eof :: proc "c" (h: ^Fofoca_Pipe, to: cstring) -> c.long {return 0}
fofoca_peers_json :: proc "c" (h: ^Fofoca_Pipe, buf: [^]u8, cap: c.size_t) -> c.long {return 0}
fofoca_state_json :: proc "c" (h: ^Fofoca_Pipe, buf: [^]u8, cap: c.size_t) -> c.long {return 0}
fofoca_state_merge :: proc "c" (h: ^Fofoca_Pipe, merge_json: cstring) -> c.long {return 0}
fofoca_peer_count :: proc "c" (h: ^Fofoca_Pipe) -> c.long {return 0}
fofoca_max_chunk :: proc "c" (h: ^Fofoca_Pipe) -> c.size_t {return 0}
fofoca_close :: proc "c" (h: ^Fofoca_Pipe) {}
fofoca_last_error :: proc "c" () -> cstring {return "fofoca disabled in this build"}
fofoca_version :: proc "c" () -> cstring {return "stub"}

FOFOCA_DEFAULT_MAX_PEERS :: 64

@(private = "file")
fofoca_sized_json :: proc(
	h: ^Fofoca_Pipe,
	fn: proc "c" (h: ^Fofoca_Pipe, buf: [^]u8, cap: c.size_t) -> c.long,
	allocator: mem.Allocator,
) -> string {
	cap_hint := 0
	for _ in 0 ..< 4 {
		needed := fn(h, nil, 0)
		if needed <= 0 {
			return ""
		}
		ncap := max(int(needed) + 1 + 64, cap_hint)
		buf := make([]u8, ncap, allocator)
		n := fn(h, raw_data(buf), c.size_t(len(buf)))
		if n <= 0 {
			return ""
		}
		if int(n) < len(buf) {
			return string(buf[:n])
		}
		cap_hint = int(n) + 1 + 64
	}
	return ""
}

fofoca_peers_json_string :: proc(h: ^Fofoca_Pipe, allocator: mem.Allocator) -> string {
	return fofoca_sized_json(h, fofoca_peers_json, allocator)
}

fofoca_state_json_string :: proc(h: ^Fofoca_Pipe, allocator: mem.Allocator) -> string {
	return fofoca_sized_json(h, fofoca_state_json, allocator)
}

fofoca_clone_cstring :: proc(s: cstring, allocator := context.allocator) -> string {
	if s == nil {
		return ""
	}
	out, _ := strings.clone_from_cstring(s, allocator)
	return out
}

fofoca_last_error_string :: proc(allocator := context.temp_allocator) -> string {
	return fofoca_clone_cstring(fofoca_last_error(), allocator)
}
ODIN
}

prepare_nomesh_tree() {
	local tree="$WORK/src-nomesh"
	rm -rf "$tree"
	mkdir -p "$tree"
	# -a keeps the tree an exact copy; only mesh.odin is then swapped.
	rsync -a --delete "$ROOT/src/" "$tree/"
	write_nomesh_stub "$tree/fofoca.odin"
	# main.odin reaches out of the package with `import k2 "../karl2d"` and
	# `#load("../assets/...")`, so the copy's parent has to look like the repo
	# root. Symlinks, not copies — karl2d alone is large.
	for d in karl2d assets fofoca; do
		ln -sfn "$ROOT/$d" "$WORK/$d"
	done
	echo "$tree"
}

#-----------------------------------------------------------------------------#
# size
#-----------------------------------------------------------------------------#
build_variants() {
	local tree
	tree="$(prepare_nomesh_tree)"

	log "building mesh binary (-o:speed)"
	just fofoca >/dev/null
	odin build src -o:speed "${DEFINES[@]}" -out:"$OUT/mallorca-mesh" 2>&1 | grep -v 'duplicate librar' || true

	log "building no-mesh baseline (-o:speed)"
	odin build "$tree" -o:speed "${DEFINES[@]}" -out:"$OUT/mallorca-nomesh" 2>&1 | grep -v 'duplicate librar' || true

	log "building -o:size variants (reduction lever)"
	odin build src -o:size "${DEFINES[@]}" -out:"$OUT/mallorca-mesh-osize" 2>&1 | grep -v 'duplicate librar' || true
	odin build "$tree" -o:size "${DEFINES[@]}" -out:"$OUT/mallorca-nomesh-osize" 2>&1 | grep -v 'duplicate librar' || true

	log "building profile binary (-define:MALLORCA_PROFILE=true)"
	odin build src -o:speed "${DEFINES[@]}" -define:MALLORCA_PROFILE=true \
		-out:"$OUT/mallorca-prof" 2>&1 | grep -v 'duplicate librar' || true
	odin build "$tree" -o:speed "${DEFINES[@]}" -define:MALLORCA_PROFILE=true \
		-out:"$OUT/mallorca-nomesh-prof" 2>&1 | grep -v 'duplicate librar' || true

	for v in mallorca-mesh mallorca-nomesh mallorca-mesh-osize mallorca-nomesh-osize; do
		cp "$OUT/$v" "$OUT/$v.stripped"
		strip -x "$OUT/$v.stripped"
	done
}

measure_size() {
	build_variants

	log "collecting sizes"
	{
		echo "variant	bytes"
		for v in mallorca-mesh mallorca-nomesh mallorca-mesh-osize mallorca-nomesh-osize; do
			echo "$v	$(bytes "$OUT/$v")"
			echo "$v.stripped	$(bytes "$OUT/$v.stripped")"
		done
		local ar="fofoca/lib/libfofoca_ffi.a"
		[ -f "$ar" ] && echo "staticlib.a	$(bytes "$ar")"
	} >"$OUT/size.tsv"

	log "collecting per-section breakdown"
	size -m "$OUT/mallorca-mesh" >"$OUT/sections-mesh.txt"
	size -m "$OUT/mallorca-nomesh" >"$OUT/sections-nomesh.txt"
	# Join the two `size -m` outputs on section name and diff them.
	{
		echo "segment	section	fofoca_bytes	nomesh_bytes	delta"
		awk '
			/^Segment/ { seg = $2; sub(/:$/, "", seg); next }
			/^\tSection/ { sec = $2; sub(/:$/, "", sec); print seg "\t" sec "\t" $3 }
		' "$OUT/sections-mesh.txt" | sort >"$WORK/sec-mesh"
		awk '
			/^Segment/ { seg = $2; sub(/:$/, "", seg); next }
			/^\tSection/ { sec = $2; sub(/:$/, "", sec); print seg "\t" sec "\t" $3 }
		' "$OUT/sections-nomesh.txt" | sort >"$WORK/sec-nomesh"
		join -t'	' -j1 -a1 -a2 -e 0 -o 0,1.2,2.2 \
			<(awk -F'\t' '{print $1"/"$2"\t"$3}' "$WORK/sec-mesh") \
			<(awk -F'\t' '{print $1"/"$2"\t"$3}' "$WORK/sec-nomesh") |
			awk -F'\t' '{split($1,p,"/"); printf "%s\t%s\t%d\t%d\t%d\n", p[1], p[2], $2, $3, $2-$3}' |
			sort -t'	' -k5 -rn
	} >"$OUT/sections.tsv"

	attribute_crates
	rollup_families
	report_size
}

